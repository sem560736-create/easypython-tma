from typing import Dict, List


class Lesson:
    def __init__(
        self,
        *,
        id: int,
        title: str,
        theory: str,
        exercise: str,
        hint: str,
        correct_answer: str,
        correct_feedback: str,
        wrong_feedback: str,
        quiz: List[Dict] | None = None,
        fix_hint: str = "",
    ) -> None:
        self.id = id
        self.title = title
        self.theory = theory
        self.exercise = exercise
        self.hint = hint
        self.correct_answer = correct_answer
        self.correct_feedback = correct_feedback
        self.wrong_feedback = wrong_feedback
        self.quiz = quiz or []
        self.fix_hint = fix_hint

    def check_answer(self, user_answer: str) -> bool:
        """Проверяет, содержит ли ответ пользователя правильный ответ."""
        normalized_correct = self.correct_answer.strip().lower().replace('"', "'")
        normalized_user = user_answer.strip().lower().replace('"', "'")

        # Для заданий с переменными: принимаем любые значения, если структура верная
        lines = [l.strip() for l in normalized_user.splitlines() if l.strip()]
        
        # Проверяем наличие 3+ строк с присваиванием и print (отдельные строки)
        if len(lines) >= 3 and all("=" in l for l in lines[:3]) and any("print(" in l for l in lines):
            return True
        
        # Для урока 2: проверяем однострочный вариант с запятой
        # НЕ принимаем присваивание внутри print(...)
        if "=" in normalized_user and ("alex" in normalized_user or "25" in normalized_user or "true" in normalized_user):
            # Только если есть print() отдельно от присваивания
            if "print(" in normalized_user and "print(" not in normalized_user.split("=")[0]:
                return True

        return normalized_correct in normalized_user

    def check_quiz(self, question_index: int, option_index: int) -> bool:
        """Проверяет правильность выбранного варианта в квизе."""
        if question_index < 0 or question_index >= len(self.quiz):
            return False
        correct_option_index = self.quiz[question_index]["correct"]
        return option_index == correct_option_index


